export function lessons(): Lesson[] { return LESSONS; }
export function lesson(slug: string): Lesson | null { return LESSONS.find((l) => l.slug === slug) || null; }
/** the lesson before and after this one (for the "আগের / পরের লেসন" links) */
export function around(slug: string): { prev: Lesson | null; next: Lesson | null } {
  const i = LESSONS.findIndex((l) => l.slug === slug);
  return { prev: i > 0 ? LESSONS[i - 1] : null, next: i >= 0 && i < LESSONS.length - 1 ? LESSONS[i + 1] : null };
}
